#!/usr/bin/env node
/*
 * Builds modern-events-calendar-lite/assets/css/magenda.min.css: the rules of
 * frontend.min.css that a page showing only the magenda (Weekly View) uses.
 * Pages like that load this file instead of frontend.min.css (640 KB) and
 * iconfonts.css; the full files load when an event popup opens.
 *
 *   node tests/build-magenda-css.js           rebuild the file
 *   node tests/build-magenda-css.js --check   fail if it is out of date
 *
 * Kept: every rule that mentions mec-magenda (the skin's own styles, in all
 * states), MEC's icon glyphs (.mec-sl-*), @font-face rules, the @keyframes
 * they use, and the base MEC rules in ANCHORS. ANCHORS came from matching
 * every frontend.min.css rule against adventistai.lt's front page across
 * several months (2026-10-07); a rule is kept when any part of its selector
 * list equals an anchor. No dependencies: the minified CSS is split by braces.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'modern-events-calendar-lite', 'assets', 'css');
const source = path.join(dir, 'frontend.min.css');
const target = path.join(dir, 'magenda.min.css');

const ANCHORS = [
    '.mec-wrap',
    '.mec-wrap *',
    '.mec-wrap :after',
    '.mec-wrap h4',
    '.mec-wrap h4 a',
    '.mec-wrap.colorskin-custom h4 a:hover',
    '.mec-wrap .button',
    '.mec-wrap button',
    '.mec-wrap .mec-clear:after',
    '.mec-wrap .mec-event-article .mec-color-hover',
    '.mec-wrap .mec-color-hover:hover',
    '.mec-wrap .mec-labels-normal .mec-label-normal',
    '.mec-wrap.colorskin-custom .mec-color',
    'body[class*=mec-theme] .mec-wrap a',
    '.mec-color',
    '.mec-util-hidden',
    '.mec-expired-normal-label',
    '.event-color',
    '.mec-weekly-contents-wrapper',
    '.mec-weekly-view-date-events',
    'ul.mec-weekly-view-dates-events',
    'ul.mec-weekly-view-dates-events article:before',
    '[class*=mec-sl-]',
];

/** Comparable form of a selector: no whitespace or quotes, ':' for '::'. */
function normalize(selector) {
    return selector.replace(/\/\*[\s\S]*?\*\//g, '').replace(/['"\s]/g, '').replace(/::/g, ':');
}

/** Splits CSS into top-level blocks: {prelude, body} (body without braces). */
function blocks(css) {
    const out = [];
    let i = 0;
    while (i < css.length) {
        const open = css.indexOf('{', i);
        if (open === -1) break;
        let depth = 1;
        let j = open + 1;
        let quote = '';
        for (; j < css.length && depth > 0; j++) {
            const c = css[j];
            if (quote) {
                if (c === '\\') j++;
                else if (c === quote) quote = '';
            } else if (c === '"' || c === "'") quote = c;
            else if (c === '/' && css[j + 1] === '*') j = css.indexOf('*/', j + 2) + 1;
            else if (c === '{') depth++;
            else if (c === '}') depth--;
        }
        out.push({prelude: css.slice(i, open).replace(/\/\*[\s\S]*?\*\//g, '').trim(), body: css.slice(open + 1, j - 1)});
        i = j;
    }
    return out;
}

const anchors = new Set(ANCHORS.map(normalize));
const found = new Set();

function keepRule(prelude) {
    if (/mec-magenda/.test(prelude) || /\.mec-sl-[a-z0-9-]+/.test(prelude) && !/\s/.test(prelude.replace(/,\s*/g, ','))) return true;
    let keep = false;
    for (const part of prelude.split(',')) {
        const key = normalize(part);
        if (anchors.has(key)) {
            found.add(key);
            keep = true;
        }
    }
    return keep;
}

function build() {
    // Comments go first: one above the magenda styles contains braces.
    // Same output on Windows (CRLF checkouts) and in CI.
    const css = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n').replace(/\/\*[\s\S]*?\*\//g, '');
    const kept = [];
    const keyframes = new Map();
    for (const block of blocks(css)) {
        const prelude = block.prelude;
        if (/^@font-face/i.test(prelude)) kept.push(prelude + '{' + block.body + '}');
        else if (/^@(-webkit-)?keyframes/i.test(prelude)) keyframes.set(prelude.split(/\s+/)[1], prelude + '{' + block.body + '}');
        else if (/^@(media|supports)/i.test(prelude)) {
            const inner = blocks(block.body).filter((rule) => !rule.prelude.startsWith('@') && keepRule(rule.prelude));
            if (inner.length) kept.push(prelude + '{' + inner.map((rule) => rule.prelude + '{' + rule.body + '}').join('') + '}');
        } else if (!prelude.startsWith('@') && keepRule(prelude)) kept.push(prelude + '{' + block.body + '}');
    }
    let out = kept.join('');
    for (const [name, text] of keyframes) {
        if (new RegExp('animation[^;}]*\\b' + name.replace(/[^\w-]/g, '') + '\\b').test(out)) out += text;
    }
    const missing = ANCHORS.filter((anchor) => !found.has(normalize(anchor)));
    if (missing.length) throw new Error('Anchors not found in frontend.min.css: ' + missing.join(' | '));
    return '/* Generated by tests/build-magenda-css.js from frontend.min.css; do not edit. */\n' + out + '\n';
}

const css = build();
if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== css) {
        console.error('magenda.min.css is out of date: run node tests/build-magenda-css.js');
        process.exit(1);
    }
    console.log('PASS: magenda.min.css is up to date (' + css.length + ' bytes).');
} else {
    fs.writeFileSync(target, css);
    console.log('Wrote ' + path.relative(process.cwd(), target) + ' (' + css.length + ' bytes, from ' + fs.statSync(source).size + ').');
}
